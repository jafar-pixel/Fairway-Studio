/** Prepares reviewed SQL only. This script has no database credentials or write client. */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const content = JSON.parse(fs.readFileSync(path.join(root, 'lib/studio/mockup-content.json'), 'utf8'));
const args = Object.fromEntries(process.argv.slice(2).reduce((pairs, arg, i, all) => { if (arg.startsWith('--')) pairs.push([arg.slice(2), all[i + 1]]); return pairs; }, []));
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
if (!uuid.test(args.workspace || '') || !uuid.test(args.actor || '')) throw Error('Supply explicit --workspace UUID and --actor owner UUID. No remote changes are made.');
const wid = args.workspace, actor = args.actor;
const originals = JSON.parse(fs.readFileSync(path.join(root, 'scripts/private-original-content.json'), 'utf8'));
if (originals.workspace_id !== wid) throw Error('Original artwork import is bound to its authorized workspace.');
content.versions.push(...originals.versions); content.nodes.push(...originals.nodes);
const id = (kind, key) => { const b = createHash('sha1').update(`fairway-studio:${content.import_batch}:${wid}:${kind}:${key}`).digest().subarray(0, 16); b[6] = (b[6] & 15) | 80; b[8] = (b[8] & 63) | 128; const h=b.toString('hex'); return `${h.slice(0,8)}-${h.slice(8,12)}-${h.slice(12,16)}-${h.slice(16,20)}-${h.slice(20)}`; };
const assetHashes = {}, missing = [];
for (const asset of new Set(content.versions.map(v => v.asset).filter(Boolean))) {
 if (!/^\/(?:mockup|original)-assets\/[a-z0-9-]+\.png$/.test(asset)) throw Error('Invalid bundled asset path');
 const local = asset.startsWith('/original-assets/') ? path.join(root,'assets/originals',path.basename(asset)) : path.join(root,'public',asset);
 if (!fs.existsSync(local)) { missing.push(asset); continue; }
 assetHashes[asset] = createHash('sha256').update(fs.readFileSync(local)).digest('hex');
}
if (missing.length) throw Error(`Wait for the complete reviewed asset set before preparing import: ${missing.join(', ')}`);
fs.writeFileSync(path.join(root,'lib/studio/mockup-asset-hashes.json'), JSON.stringify(assetHashes, null, 2)+'\n');
const payload = {
 batch: content.import_batch, workspace: wid, actor,
 projects: content.projects.map(p => ({...p,id:id('project',p.key)})),
 ideas: content.ideas.map(i => ({...i,id:id('idea',i.key)})),
 tasks: content.tasks.map(t => ({...t,id:id('task',t.key)})),
 versions: content.versions.map(v => { const {key,demo_id,title,project,body,asset,...metadata}=v; return {key,id:id('version',key),title,project,body,asset,provenance:{...metadata,import_key:key,import_batch:content.import_batch,mockup_import:true,type:'mockup_import',starter_collection:true,media_origin:metadata.media_origin || 'bundled_exploratory',project_key:project,task_ids:content.tasks.filter(t=>(metadata.task_titles || []).includes(t.title)).map(t=>id('task',t.key)),import_asset_path:asset,asset_sha256:asset ? assetHashes[asset] : null,source:metadata.media_origin === 'bundled_original' ? 'User-supplied original artwork' : 'Recreated from supplied Fairway Studio mockup',generated_for_import:Boolean(asset) && metadata.media_origin !== 'bundled_original',approval_status:'unapproved',original_in_app_generation:false}}; }),
 nodes: content.nodes.map(n=>({...n,id:id('node',n.key)})),
 threads: [...content.threads, {key:'how-to',title:'How to use Fairway Studio',project:null,description:'Illustrative walkthrough; example responses are not real founder messages.'}].map(t=>({...t,id:id('thread',t.key)})),
 messages: [
  'How-to example: this walkthrough shows how to connect an idea, project, reference, and task. The example responses below are supplied instructional content, not messages sent by the named founders. Your real project conversations are ready for new discussion.',
  'Example response (not sent by Jafar): “Can we make the tech feel built into the bag?”',
  'Example response (not sent by Arlin): “Keep the silhouette clean and the pockets easy to reach.”',
  'Example response (not sent by Kyle): “Let’s compare the seam and trim placement.”',
  'Example suggested next step from the mockup: compare a concealed module with an integrated side panel. Open Signature golf bag to compare the saved exploratory concepts, or use the starter task “Compare concealed tech layouts”. This is instructional text, not a completed AI analysis.'
 ].map((body,i)=>({id:id('message',String(i)),body})),
 activity_id:id('activity','import'),
};
const encoded=JSON.stringify(payload);
if (encoded.includes('$content$')) throw Error('Unsafe SQL delimiter');
const sql=`-- REVIEWED INSERT-ONLY STARTER CONTENT IMPORT. Generated by scripts/prepare-mockup-import.mjs.
-- No schema, role, membership, settings, existing records, or approval state is changed.
-- Bundled source hashes describe the reviewed deployment; no private storage upload is asserted.
begin;
set local statement_timeout = '30s';
do $import$
declare
 p jsonb := $content$${encoded}$content$::jsonb;
 w uuid := (p->>'workspace')::uuid; actor uuid := (p->>'actor')::uuid;
 r jsonb; chosen uuid; project uuid; version uuid; old_count integer;
 projects jsonb := '{}'; ideas jsonb := '{}'; versions jsonb := '{}'; threads jsonb := '{}';
begin
 if not exists(select 1 from public.workspace_members where workspace_id=w and user_id=actor and role='owner') then raise exception 'Import actor must be the existing workspace owner'; end if;
 perform pg_advisory_xact_lock(hashtextextended('fairway-starter:' || w::text,0));
 for r in select value from jsonb_array_elements(p->'projects') loop
  chosen := null;
  select id into chosen from public.studio_projects where id=(r->>'id')::uuid and workspace_id=w;
  if chosen is null then
   select count(*),min(id::text)::uuid into old_count,chosen from public.studio_projects where workspace_id=w and lower(trim(title))=lower(trim(r->>'title'));
   if old_count>1 then raise exception 'Ambiguous existing project: %',r->>'title'; end if;
  end if;
  if chosen is null then
   chosen:=(r->>'id')::uuid;
   insert into public.studio_projects(id,workspace_id,title,brief,category,status,lead_id,created_by) values(chosen,w,r->>'title',r->>'brief',r->>'category','exploring',null,actor);
  end if;
  projects:=projects || jsonb_build_object(r->>'key',chosen);
 end loop;
 for r in select value from jsonb_array_elements(p->'ideas') loop
  chosen:=null; project:=(projects->>(r->>'project'))::uuid;
  select id into chosen from public.brand_ideas where id=(r->>'id')::uuid and workspace_id=w;
  if chosen is null then
   select count(*),min(id::text)::uuid into old_count,chosen from public.brand_ideas where workspace_id=w and lower(trim(title))=lower(trim(r->>'title'));
   if old_count>1 then raise exception 'Ambiguous existing idea: %',r->>'title'; end if;
  end if;
  if chosen is null then
   chosen:=(r->>'id')::uuid;
   insert into public.brand_ideas(id,workspace_id,author_id,title,body,category,status,tags,project_id) values(chosen,w,actor,r->>'title',r->>'body',r->>'category','exploring',array(select jsonb_array_elements_text(coalesce(r->'tags','[]'::jsonb))) || array['Starter collection','mockup-idea:'||(r->>'key')],project);
  end if;
  ideas:=ideas || jsonb_build_object(r->>'key',chosen);
 end loop;
 for r in select value from jsonb_array_elements(p->'versions') loop
  chosen:=null; project:=(projects->>(r->>'project'))::uuid;
  select id into chosen from public.studio_versions where id=(r->>'id')::uuid and workspace_id=w;
  if chosen is null then
   select count(*),min(id::text)::uuid into old_count,chosen from public.studio_versions where workspace_id=w and project_id=project and provenance->>'import_batch'=p->>'batch' and provenance->>'import_key'=r->>'key';
   if old_count>1 then raise exception 'Ambiguous imported version: %',r->>'key'; end if;
  end if;
  if chosen is null then
   chosen:=(r->>'id')::uuid;
   insert into public.studio_versions(id,workspace_id,project_id,title,body,image_url,source_url,media_verification,provenance,created_by) values(chosen,w,project,r->>'title',r->>'body',null,null,case when r->>'asset' is null then 'text_only' else coalesce(r->'provenance'->>'media_origin','bundled_exploratory') end,r->'provenance',actor);
  end if;
  versions:=versions || jsonb_build_object(r->>'key',chosen);
 end loop;
 for r in select value from jsonb_array_elements(p->'ideas') loop
  -- Natural-key matches remain untouched, including their link graph and revision.
  if (ideas->>(r->>'key'))::uuid <> (r->>'id')::uuid then continue; end if;
  insert into public.studio_idea_assets(id,workspace_id,idea_id,version_id,created_by)
   select md5(w::text||':starter-idea-asset:'||(r->>'key'))::uuid,w,(ideas->>(r->>'key'))::uuid,(versions->>(r->>'version'))::uuid,actor
   where not exists(select 1 from public.studio_idea_assets where workspace_id=w and idea_id=(ideas->>(r->>'key'))::uuid and version_id=(versions->>(r->>'version'))::uuid) on conflict do nothing;
  insert into public.studio_idea_projects(id,workspace_id,idea_id,project_id,created_by)
   select md5(w::text||':starter-idea-project:'||(r->>'key'))::uuid,w,(ideas->>(r->>'key'))::uuid,(projects->>(r->>'project'))::uuid,actor
   where not exists(select 1 from public.studio_idea_projects where workspace_id=w and idea_id=(ideas->>(r->>'key'))::uuid and project_id=(projects->>(r->>'project'))::uuid) on conflict do nothing;
 end loop;
 for r in select value from jsonb_array_elements(p->'tasks') loop
  project:=(projects->>(r->>'project'))::uuid;
  if not exists(select 1 from public.studio_tasks where workspace_id=w and (id=(r->>'id')::uuid or lower(trim(title))=lower(trim(r->>'title')))) then
   insert into public.studio_tasks(id,workspace_id,created_by,title,details,category,status,assigned_to,project_id,priority,checklist)
    values((r->>'id')::uuid,w,actor,r->>'title',(r->>'details')||E'\n\n[Fairway starter] Imported task suggestion; choose an assignee and status when ready.',r->>'category','open',null,project,'normal',coalesce(r->'checklist','[]'::jsonb));
  end if;
 end loop;
 for r in select value from jsonb_array_elements(p->'nodes') loop
  insert into public.studio_canvas_nodes(id,workspace_id,project_id,version_id,kind,body,x,y,width,height)
   values((r->>'id')::uuid,w,(projects->>(r->>'project'))::uuid,(versions->>(r->>'version'))::uuid,r->>'kind',r->>'body',(r->>'x')::float,(r->>'y')::float,(r->>'width')::float,(r->>'height')::float) on conflict(id) do nothing;
 end loop;
 for r in select value from jsonb_array_elements(p->'threads') loop
  chosen:=null; project:=(projects->>(r->>'project'))::uuid;
  select id into chosen from public.studio_threads where workspace_id=w and id=(r->>'id')::uuid;
  if chosen is null and project is not null then select id into chosen from public.studio_threads where workspace_id=w and project_id=project and idea_id is null and task_id is null; end if;
  if chosen is null then
   select count(*),min(id::text)::uuid into old_count,chosen from public.studio_threads where workspace_id=w and project_id is not distinct from project and lower(trim(title))=lower(trim(r->>'title'));
   if old_count>1 then raise exception 'Ambiguous existing thread: %',r->>'title'; end if;
  end if;
  if chosen is null then
   chosen:=(r->>'id')::uuid;
   insert into public.studio_threads(id,workspace_id,title,project_id,created_by) values(chosen,w,r->>'title',project,actor);
  end if;
  threads:=threads || jsonb_build_object(r->>'key',chosen);
 end loop;
 for r in select value from jsonb_array_elements(p->'messages') loop
  insert into public.workspace_messages(id,workspace_id,thread_id,author_id,body,client_request_id)
   values((r->>'id')::uuid,w,(threads->>'how-to')::uuid,actor,r->>'body',(r->>'id')::uuid) on conflict(id) do nothing;
 end loop;
 insert into public.studio_activity(id,workspace_id,actor_id,operation,payload)
  values((p->>'activity_id')::uuid,w,actor,'importStarterCollection',jsonb_build_object('import_batch',p->>'batch','source','Supplied Fairway Studio how-to mockups','projects',projects,'ideas',ideas,'versions',versions,'threads',threads,'approvals_created',false,'generation_claimed',false)) on conflict(id) do nothing;
end $import$;
commit;
`;
const output=path.resolve(args.output || path.join(root,'supabase/mockup-content-import.sql'));
fs.writeFileSync(output,sql);
fs.writeFileSync(output.replace(/\.sql$/,'.manifest.json'),JSON.stringify(payload,null,2)+'\n');
console.log(JSON.stringify({prepared_only:true,output,workspace:wid,actor,counts:Object.fromEntries(['projects','ideas','versions','tasks','nodes','threads','messages'].map(k=>[k,payload[k].length])),asset_count:Object.keys(assetHashes).length},null,2));
